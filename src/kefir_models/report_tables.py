"""Generate the report's numerical tables and values from saved experiment CSVs."""

from __future__ import annotations

import argparse
import json
from pathlib import Path

import numpy as np
import pandas as pd


def latex_table(
    caption: str, label: str, columns: str, header: str, rows: list[str], *, resize: bool = True
) -> str:
    opening = (
        "\\resizebox{\\textwidth}{!}{%\n"
        if resize
        else ("\\begingroup\\small\\setlength{\\tabcolsep}{4pt}\n")
    )
    closing = "}\n" if resize else "\\endgroup\n"
    return (
        "\\begin{table}[htbp]\n\\centering\n"
        f"\\caption{{{caption}}}\n\\label{{{label}}}\n"
        + opening
        + f"\\begin{{tabular}}{{{columns}}}\n\\toprule\n"
        + header
        + " \\\\\n\\midrule\n"
        + "\n".join(row + " \\\\" for row in rows)
        + "\n\\bottomrule\n\\end{tabular}\n"
        + closing
        + "\\end{table}\n"
    )


def generate_tables(neural_dir: Path, pinn_dir: Path, output_dir: Path) -> None:
    neural = pd.read_csv(neural_dir / "model_comparison_metrics.csv")
    pinn = pd.read_csv(pinn_dir / "water_kefir_logistic_pinn_metrics.csv")
    metrics = pd.concat([neural, pinn], ignore_index=True)
    required = [
        "model",
        "rmse",
        "r_squared",
        "aic",
        "bic",
        "parameter_count",
        "likelihood_parameter_count",
        "observation_count",
        "interval_coverage",
        "mean_interval_width",
    ]
    missing = set(required).difference(metrics.columns)
    if missing:
        raise ValueError(f"Missing report metrics: {sorted(missing)}")
    numeric = [
        "rmse",
        "r_squared",
        "aic",
        "bic",
        "parameter_count",
        "likelihood_parameter_count",
        "observation_count",
    ]
    if not np.isfinite(metrics[numeric].to_numpy(dtype=float)).all():
        raise ValueError("Report metrics must be finite.")
    if len(metrics) != 6 or metrics.model.duplicated().any():
        raise ValueError("Expected six distinct model comparison rows.")
    rows = [
        f"{r.model} & {r.rmse:.4f} & {r.r_squared:.4f} & {r.aic:.2f} & {r.bic:.2f}"
        f" & {int(r.parameter_count)} & {int(r.likelihood_parameter_count)}"
        for r in metrics.itertuples()
    ]
    content = "% Generated by kefir_models.report_tables; do not edit manually.\n"
    content += latex_table(
        "In-sample comparison on the original response scale. AIC and BIC here "
        "are Gaussian residual complexity scores, not a common fitted likelihood "
        "for all model families.",
        "tab:metrics",
        "lrrrrrr",
        "Model & RMSE & $R^2$ & AIC & BIC & $p$ & $k$",
        rows,
    )
    stochastic = metrics.loc[metrics.interval_coverage.notna()]
    content += latex_table(
        "Conditional process-noise diagnostics with fitted parameters held fixed.",
        "tab:sde-intervals",
        "lrr",
        "Model & 90 percent coverage & Mean width",
        [
            f"{r.model} & {r.interval_coverage:.4f} & {r.mean_interval_width:.4f}"
            for r in stochastic.itertuples()
        ],
    )
    parameters = pd.read_csv(pinn_dir / "water_kefir_logistic_pinn_parameters.csv")
    physical = parameters.pivot(index="model", columns="parameter", values="value")
    det = physical.loc["deterministic_logistic_pinn"]
    sto = physical.loc["stochastic_logistic_sde"]
    content += latex_table(
        "Estimated logistic PINN parameters on the original time scale.",
        "tab:pinn-parameters",
        "lrrr",
        "Model & $r$ & $K$ & $\\sigma$",
        [
            f"Deterministic logistic PINN & {det.growth_rate:.6f} & "
            f"{det.carrying_capacity:.4f} & --",
            f"Stochastic logistic PINN/SDE & {sto.growth_rate:.6f} & "
            f"{sto.carrying_capacity:.4f} & {sto.diffusion:.6f}",
        ],
    )
    classical = pd.read_csv(neural_dir / "classical_logistic_parameters.csv").set_index("parameter")
    # The time-scale factor is saved with the effective run, not assumed to be 168.
    metadata = json.loads((neural_dir / "run_metadata.json").read_text(encoding="utf-8"))
    scale = float(metadata["diagnostics"]["time_scale"])
    values = {
        "classicrNormalized": f"{classical.loc['growth_rate', 'value']:.6f}",
        "classicrOriginal": f"{classical.loc['growth_rate', 'value'] / scale:.6f}",
        "classicK": f"{classical.loc['carrying_capacity', 'value']:.6f}",
        "detR": f"{det.growth_rate:.6f}",
        "detK": f"{det.carrying_capacity:.4f}",
        "stoR": f"{sto.growth_rate:.6f}",
        "stoK": f"{sto.carrying_capacity:.4f}",
        "stoSigma": f"{sto.diffusion:.6f}",
    }
    for name, model in (("neural", "Neural SDE"), ("logistic", "Stochastic Logistic SDE Mean")):
        row = metrics.set_index("model").loc[model]
        values[f"{name}Coverage"] = f"{row.interval_coverage:.4f}"
        values[f"{name}Covered"] = str(round(row.interval_coverage * row.observation_count))
    values["observationCount"] = str(int(metrics.observation_count.iloc[0]))
    macros = "% Generated by kefir_models.report_tables; do not edit manually.\n"
    macros += (
        "\n".join(f"\\newcommand{{\\{key}}}{{{value}}}" for key, value in values.items()) + "\n"
    )
    output_dir.mkdir(parents=True, exist_ok=True)
    (output_dir / "model_comparison_tables.tex").write_text(content, encoding="utf-8")
    (output_dir / "fit_values.tex").write_text(macros, encoding="utf-8")
    metrics.to_csv(output_dir / "model_comparison_metrics.csv", index=False)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--neural-dir", type=Path, default=Path("results/neural_sde_comparison_outputs")
    )
    parser.add_argument("--pinn-dir", type=Path, default=Path("results/logistic_pinn_outputs"))
    parser.add_argument("--output-dir", type=Path, default=Path("docs/generated"))
    args = parser.parse_args()
    generate_tables(args.neural_dir, args.pinn_dir, args.output_dir)


if __name__ == "__main__":
    main()
