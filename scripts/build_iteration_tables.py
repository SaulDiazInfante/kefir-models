"""Generate LaTeX tables from the controlled calibration experiment outputs."""

from __future__ import annotations

from functools import partial
from pathlib import Path

import pandas as pd

from kefir_models.report_tables import latex_table as base_latex_table

latex_table = partial(base_latex_table, resize=False)


def main():
    root = Path("results/rev07")
    frozen = (
        pd.read_csv(root / "frozen/transitions.csv").groupby("substeps").mean(numeric_only=True)
    )
    by_fit = pd.read_csv(root / "by_fit.csv")
    full = by_fit.loc[by_fit.cutoff == 168].groupby("model").forecast_coverage.mean()
    held = pd.read_csv(root / "holdout_summary.csv").groupby("model").mean(numeric_only=True)
    labels = {
        "wide_euler": "Wide Euler",
        "wide_moments": "Wide moments",
        "compact_euler": "Small Euler",
        "compact_moments": "Small moments",
        "compact_moments_regularized": "Small moments + L2",
        "classical_observation_noise": "Logistic + observation noise",
    }
    content = "% Generated by scripts/build_iteration_tables.py; do not edit manually.\n"
    content += latex_table(
        "Frozen reference coefficients: conditional simulations averaged over three seeds.",
        "tab:frozen-transitions",
        "rrrr",
        "Substeps & RMSE & Coverage & RMS mean shift",
        [
            f"{int(step)} & {r.conditional_rmse:.4f} & {r.coverage:.4f} & "
            f"{r.mean_shift_from_euler_rms:.4f}"
            for step, r in frozen.iterrows()
        ],
    )
    content += latex_table(
        "Controlled candidates: nominal interval level 0.90. "
        "Held-out summaries reuse observations across cutoffs.",
        "tab:rev07-forecast",
        "lrrrr",
        "Candidate & Full-data coverage & Held-out coverage & RMSE & Width",
        [
            f"{label} & {full[name]:.4f} & {held.loc[name, 'coverage']:.4f} & "
            f"{held.loc[name, 'rmse']:.4f} & {held.loc[name, 'mean_width']:.4f}"
            for name, label in labels.items()
        ],
    )
    Path("docs/generated/rev07_tables.tex").write_text(content, encoding="utf-8")


if __name__ == "__main__":
    main()
