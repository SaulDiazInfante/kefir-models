"""Generate the moment-controlled prior comparison tables from saved CSVs."""

from __future__ import annotations

from functools import partial
from pathlib import Path

import pandas as pd

from kefir_models.report_tables import latex_table as base_latex_table

latex_table = partial(base_latex_table, resize=False)
ROOT = Path("results/tempered")
LABELS = {
    "independent_ou": "Independent OU",
    "shared_ou": "Shared OU",
    "independent_matern32": r"Independent Mat\'ern",
    "shared_matern32": r"Shared Mat\'ern",
}


def main():
    prior = pd.read_csv(ROOT / "prior_checks.csv")
    summary = pd.read_csv(ROOT / "forecast_summary.csv")
    checks = pd.read_csv(ROOT / "computation_checks.csv")
    refinement = pd.read_csv(ROOT / "predictive_integration_refinement.csv")
    parameters = pd.read_csv(ROOT / "full_data_parameters.csv")
    historical = pd.read_csv(ROOT / "historical_reference_scores.csv")
    tables = "% Generated by scripts/build_tempered_tables.py; do not edit manually.\n"
    tables += latex_table(
        "Normalized noise-SD priors: median matched to 0.03. Gaussian kernel "
        "locations are not means of the tempered log-SD distribution.",
        "tab:tempered-priors",
        "rrrrrr",
        r"$\eta$ & Kernel location & $\log Z_\eta$ & SD 5th & SD median & SD 95th",
        [
            f"{r.eta:g} & {r.kernel_location:.5f} & {r.log_normalizer_per_sd:.5f} & "
            f"{r.sd_q05:.5f} & {r.sd_median:.5f} & {r.sd_q95:.5f}"
            for r in prior.itertuples()
        ],
    )
    rollout = summary.loc[summary.task == "rollout"]
    tables += latex_table(
        "Tempered-prior multi-time holdouts: 36 overlapping entries per row. "
        "Lower IS and negative log predictive density are preferable.",
        "tab:tempered-rollout",
        "lrrrrrr",
        r"Model & $\eta$ & Cov. & Width & IS & Marg. NLL & Joint NLL",
        [
            f"{LABELS[r.model]} & {r.eta:g} & {r.coverage:.4f} & {r.mean_width:.3f} & "
            f"{r.interval_score:.3f} & {r.marginal_predictive_nll:.3f} & "
            f"{r.joint_predictive_nll_per_entry:.3f}"
            for r in rollout.itertuples()
        ],
    )
    one = summary.loc[summary.task == "one_step"].set_index("model")
    tables += latex_table(
        r"Main prior ($\eta=2$), one-step forecasts: 15 distinct scalar targets "
        "from the same three trial series. Both mean and median point errors are shown.",
        "tab:tempered-one-step",
        "lrrrrrr",
        "Model & Cov. & RMSE (mean) & RMSE (med.) & IS & Marg. NLL & Joint NLL",
        [
            f"{label} & {one.loc[m, 'coverage']:.4f} & {one.loc[m, 'rmse_mean']:.3f} & "
            f"{one.loc[m, 'rmse_median']:.3f} & {one.loc[m, 'interval_score']:.3f} & "
            f"{one.loc[m, 'marginal_predictive_nll']:.3f} & "
            f"{one.loc[m, 'joint_predictive_nll_per_entry']:.3f}"
            for m, label in LABELS.items()
        ],
    )
    capacity = parameters.loc[
        (parameters.eta == 2) & (parameters.parameter == "capacity")
    ].set_index("model")
    tables += latex_table(
        r"Full-data capacity posterior for the main tempered prior ($\eta=2$). "
        "Intervals describe parameters, not new noisy responses.",
        "tab:tempered-capacity",
        "lrrr",
        "Model & Median & 5th percentile & 95th percentile",
        [
            f"{label} & {capacity.loc[m, 'median']:.3f} & "
            f"{capacity.loc[m, 'q05']:.3f} & {capacity.loc[m, 'q95']:.3f}"
            for m, label in LABELS.items()
        ],
    )
    Path("docs/generated/tempered_tables.tex").write_text(tables)
    ref = rollout.loc[rollout.eta == 2].set_index("model")
    old = historical.loc[historical.task == "rollout"].set_index("model")
    independent, shared = ref.loc["independent_ou"], ref.loc["shared_ou"]
    text = rf"""
\subsection{{Results and interpretation}}

    Under the main tempered prior, independent OU multi-time coverage is
    {independent.coverage:.4f}, with interval score {independent.interval_score:.3f}
    and finite-mean forecast RMSE {independent.rmse_mean:.3f}.
    Shared OU coverage is {shared.coverage:.4f}, with interval score
    {shared.interval_score:.3f} and RMSE {shared.rmse_mean:.3f}.
    Mean observed-minus-mean-forecast bias remains
    {independent.bias_mean:.3f} and {shared.bias_mean:.3f}, respectively.
    These results address the moment pathology while retaining the late
    underprediction as a separate model-adequacy issue.

    The historical finite-subset independent and shared OU interval scores
    were {old.loc["independent_ou", "interval_score"]:.3f} and
    {old.loc["shared_ou", "interval_score"]:.3f}; their coverages were
    {old.loc["independent_ou", "coverage"]:.4f} and
    {old.loc["shared_ou", "coverage"]:.4f}. Those earlier mean-based quantities
    remain finite-subset diagnostics. The new predictive means have a
    mathematically finite target under the new priors. This does not make
    small differences in retrospective scores statistically decisive.

    At the 15 distinct one-step targets, independent and shared OU coverages
    are {one.loc["independent_ou", "coverage"]:.4f} and
    {one.loc["shared_ou", "coverage"]:.4f}. Their mean-forecast RMSE values are
    {one.loc["independent_ou", "rmse_mean"]:.3f} and
    {one.loc["shared_ou", "rmse_mean"]:.3f}; median-forecast RMSE values are
    {one.loc["independent_ou", "rmse_median"]:.3f} and
    {one.loc["shared_ou", "rmse_median"]:.3f}.
    Joint density scores retain the modeled dependence between trial
    responses. Table~\ref{{tab:tempered-one-step}} reports all four models;
    Table~\ref{{tab:tempered-rollout}} retains both prespecified tail strengths.

    All 40 cases meet the computation gates. The largest monitored
    $\widehat R$ is {checks.max_rhat.max():.4f}, minimum bulk ESS
    {checks.min_bulk_ess.min():.0f}, and minimum tail ESS
    {checks.min_tail_ess.min():.0f}. The minimum raw ESS for monitored
    conditional-response-mean observables is
    {checks.min_predictive_mean_raw_ess.min():.0f}; their largest estimated MCSE
    is {checks.max_estimated_mean_mcse.max():.4f} response units. Those
    functional diagnostics use every eighth retained draw. New fits retain
    {checks.draws_per_chain.min():.0f} to {checks.draws_per_chain.max():.0f}
    draws per chain after 6000 warmup iterations. They support a finite-run
    computation check, not a proof of convergence or predictive calibration.

    For the two main-prior OU models at cutoff 132, posterior integration
    using 6000, 12000, and 24000 components shifts means by at most
    {refinement.max_mean_shift_from_6000.max():.3f} response units and interval
    endpoints by at most {refinement.max_endpoint_shift_from_6000.max():.3f}
    relative to the 6000-component result. These are numerical sensitivity
    checks, distinct from the analytic moment bound.

    No discrepancy model or tail strength is promoted to the mechanistic
    reference. Prior medians are matched, but prior shapes and upper
    quantiles change. Only two fixed tail strengths were tested here;
    the earlier half/double noise-median sensitivity is not a sensitivity
    analysis of this new family. The proposed prospective protocol retains
    its earlier priors and median point forecast until explicitly amended.
    Unconfirmed physical units, experimental dependence, and unavailable
    independent trajectories remain unresolved. A finite predictive mean
    resolves REV-11's mathematical concern for this new family, while
    REV-07's predictive adequacy and REV-10's experimental validation remain open.

\begin{{figure}}[htbp]
    \centering
    \includegraphics[width=\textwidth]{{../results/tempered/noise_prior_comparison.png}}
    \caption{{Noise-SD prior densities with matched median 0.03. The stronger
    upper-tail penalties change the 95th percentiles and tail integrability;
    they impose no finite upper SD bound. Both latent and measurement SDs
    receive the same separate prior.}}
    \label{{fig:tempered-priors}}
\end{{figure}}
\begin{{figure}}[htbp]
    \centering
    \includegraphics[width=\textwidth]{{../results/tempered/forecast_comparison.png}}
    \caption{{Main tempered prior: trial 3 predictive means and central
    90 percent observation intervals. Black points are held-out responses.
    All reported metrics use the three trial series. These means estimate
    finite response expectations under the new model.}}
    \label{{fig:tempered-forecast}}
\end{{figure}}
"""
    Path("docs/generated/tempered_interpretation.tex").write_text(text)


if __name__ == "__main__":
    main()
