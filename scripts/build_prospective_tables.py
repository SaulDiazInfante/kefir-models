"""Generate report readiness tables without inventing experimental metadata."""

from __future__ import annotations

import json
from pathlib import Path

import pandas as pd

from kefir_models.ode_fit import read_trial_csv, validate_frame
from kefir_models.prospective_validation import audit_plan
from kefir_models.report_tables import latex_table


def main():
    plan_path = Path("configs/prospective_validation.json")
    plan = json.loads(plan_path.read_text())
    metadata = json.loads(Path(plan["reference_metadata"]).read_text())
    report = audit_plan(plan_path)
    root = Path("results/prospective")
    root.mkdir(parents=True, exist_ok=True)
    (root / "readiness.json").write_text(json.dumps(report, indent=2) + "\n")
    data, columns = validate_frame(read_trial_csv(Path(metadata["path"])))
    audit = pd.DataFrame(
        [
            {"item": "Development time points", "value": str(len(data))},
            {"item": "Development trial series", "value": str(len(columns))},
            {"item": "Development scalar responses", "value": str(data[columns].count().sum())},
            {"item": "Declared new independent units", "value": str(len(plan["validation_units"]))},
            {"item": "Unresolved experimental declarations", "value": str(len(report["missing"]))},
            {
                "item": "Protocol ready to freeze",
                "value": "Yes" if report["protocol_ready_to_freeze"] else "No",
            },
        ]
    )
    audit.to_csv(root / "data_audit.csv", index=False)
    design = pd.DataFrame(
        [
            {"item": "Candidate models", "value": str(len(plan["models"]))},
            {"item": "Forecast origins", "value": ", ".join(f"{v:g}" for v in plan["origins"])},
            {"item": "Forecast horizon", "value": ", ".join(f"{v:g}" for v in plan["horizons"])},
            {"item": "Observation interval level", "value": f"{plan['interval_level']:.2f}"},
            {"item": "Primary score", "value": "Central interval score"},
            {"item": "Point forecast", "value": "Posterior predictive median"},
            {"item": "Aggregation", "value": "Equal weights for independent units"},
        ]
    )
    design.to_csv(root / "draft_design.csv", index=False)
    tables = "% Generated by scripts/build_prospective_tables.py; do not edit manually.\n"
    for filename, caption, label in [
        (
            "data_audit.csv",
            "Current validation readiness. Declared new units are not inferred "
            "from trial columns or file names.",
            "tab:prospective-readiness",
        ),
        (
            "draft_design.csv",
            "Draft prospective comparison, pending experimental metadata and schedule "
            "confirmation. Times retain original numerical units.",
            "tab:prospective-design",
        ),
    ]:
        frame = pd.read_csv(root / filename, dtype=str)
        tables += latex_table(
            caption,
            label,
            "ll",
            "Item & Value",
            [f"{r.item} & {r.value}" for r in frame.itertuples()],
            resize=False,
        )
    Path("docs/generated/prospective_tables.tex").write_text(tables)


if __name__ == "__main__":
    main()
