"""Build structural-discrepancy report tables directly from experiment summaries."""

from __future__ import annotations

from functools import partial
from pathlib import Path

import pandas as pd

from kefir_models.report_tables import latex_table as base_latex_table

latex_table = partial(base_latex_table, resize=False)
ROOT = Path("results/structural")
LABELS = {
    "independent_ou": "Independent OU",
    "shared_ou": "Shared OU",
    "independent_matern32": r"Independent Mat\'ern",
    "shared_matern32": r"Shared Mat\'ern",
}


def main():
    scores = pd.read_csv(ROOT / "forecast_summary.csv")
    checks = pd.read_csv(ROOT / "computation_checks.csv")
    parameters = pd.read_csv(ROOT / "full_data_parameters.csv")
    refinement = pd.read_csv(ROOT / "predictive_integration_refinement.csv")
    content = "% Generated by scripts/build_structural_tables.py; do not edit manually.\n"
    for task, title in [
        ("rollout", "Multi-time holdouts: 36 overlapping forecast entries per model."),
        ("one_step", "One-step forecasts: 15 distinct scalar targets per model."),
    ]:
        data = scores.loc[(scores.prior == "reference") & (scores.task == task)].set_index("model")
        content += latex_table(
            title + " Reference prior; nominal coverage 0.90. IS is the interval score; "
            "NLL columns are marginal and joint per-entry negative log predictive density.",
            f"tab:structural-{task.replace('_', '-')}",
            "lrrrrr",
            "Model & Coverage & Width & IS & Marg. NLL & Joint NLL",
            [
                f"{label} & {data.loc[model, 'coverage']:.4f} & "
                f"{data.loc[model, 'mean_width']:.3f} & {data.loc[model, 'interval_score']:.3f} & "
                f"{data.loc[model, 'marginal_predictive_nll']:.3f} & "
                f"{data.loc[model, 'joint_predictive_nll_per_entry']:.3f}"
                for model, label in LABELS.items()
            ],
        )
    data = parameters.loc[
        (parameters.prior == "reference") & (parameters.parameter == "capacity")
    ].set_index("model")
    content += latex_table(
        "Full-data logistic capacity posterior under the reference prior. These "
        "are parameter credible intervals, not observation predictive intervals.",
        "tab:structural-capacity",
        "lrrr",
        "Model & Median & 5th percentile & 95th percentile",
        [
            f"{label} & {data.loc[model, 'median']:.3f} & "
            f"{data.loc[model, 'q05']:.3f} & {data.loc[model, 'q95']:.3f}"
            for model, label in LABELS.items()
        ],
    )
    sensitivity = scores.loc[scores.task == "rollout"].groupby("model")
    content += latex_table(
        "Multi-time forecast sensitivity across half, reference, and double noise-prior medians. "
        "Ranges summarize three fixed choices, not optimized hyperparameters.",
        "tab:structural-sensitivity",
        "lrrrr",
        "Model & Min. coverage & Max. coverage & Min. IS & Max. IS",
        [
            f"{label} & {sensitivity.get_group(model).coverage.min():.4f} & "
            f"{sensitivity.get_group(model).coverage.max():.4f} & "
            f"{sensitivity.get_group(model).interval_score.min():.3f} & "
            f"{sensitivity.get_group(model).interval_score.max():.3f}"
            for model, label in LABELS.items()
        ],
    )
    Path("docs/generated/structural_tables.tex").write_text(content)
    rollout = scores.loc[(scores.prior == "reference") & (scores.task == "rollout")].set_index(
        "model"
    )
    one = scores.loc[(scores.prior == "reference") & (scores.task == "one_step")].set_index("model")
    independent, shared = rollout.loc["independent_ou"], rollout.loc["shared_ou"]
    single_i, single_s = one.loc["independent_ou"], one.loc["shared_ou"]
    interpretation = rf"""
\subsection{{Results and remaining scientific limits}}

    For multi-time holdouts, reference shared OU coverage is
    {shared.coverage:.4f}, compared with {independent.coverage:.4f} for independent
    OU deviations. Mean width changes from {independent.mean_width:.3f} to
    {shared.mean_width:.3f}; interval score changes from
    {independent.interval_score:.3f} to {shared.interval_score:.3f}.
    Mean observed-minus-predicted bias remains {shared.mean_bias:.3f}
    for shared OU, versus {independent.mean_bias:.3f} for independent OU.
    Their RMSE values are {shared.rmse:.3f} and {independent.rmse:.3f}, respectively.
    Improved coverage therefore must be interpreted together with interval
    width, scoring rules, and residual bias, rather than as a correction of
    the logistic growth law.

    On the distinct one-step targets, shared and independent OU coverage are
    {single_s.coverage:.4f} and {single_i.coverage:.4f}; their interval scores are
    {single_s.interval_score:.3f} and {single_i.interval_score:.3f}.
    Marginal NLL values are {single_s.marginal_predictive_nll:.3f} and
    {single_i.marginal_predictive_nll:.3f}, and joint per-entry NLL values are
    {single_s.joint_predictive_nll_per_entry:.3f} and
    {single_i.joint_predictive_nll_per_entry:.3f}.
    The joint score evaluates the three simultaneous trial responses together,
    retaining both latent dependence and common parameter uncertainty.
    Here the shared OU model improves marginal NLL and interval score,
    whereas independent OU has the better joint predictive density score
    under both forecast summaries. This disagreement matters: the marginal
    improvement does not validate the stronger shared-dependence assumption.

    Smoother independent Mat\'ern discrepancies have multi-time coverage
    {rollout.loc["independent_matern32", "coverage"]:.4f} and mean bias
    {rollout.loc["independent_matern32", "mean_bias"]:.3f}; shared Mat\'ern
    discrepancies have coverage {rollout.loc["shared_matern32", "coverage"]:.4f}
    and bias {rollout.loc["shared_matern32", "mean_bias"]:.3f}.
    Table~\ref{{tab:structural-one-step}} reports their distinct-target scores.
    This fixed comparison does not establish that temporal smoothness resolves
    the late systematic departure. No candidate is promoted to a mechanistic
    reference on these retrospective data.

    All 56 posterior cases meet the computational thresholds: largest
    $\widehat R={checks.max_rhat.max():.4f}$, minimum bulk ESS
    {checks.min_bulk_ess.min():.0f}, and minimum tail ESS
    {checks.min_tail_ess.min():.0f}. New cases retain between
    {checks.loc[~checks.reused_upstream, "draws_per_chain"].min():.0f} and
    {checks.loc[~checks.reused_upstream, "draws_per_chain"].max():.0f} draws per chain
    after 6000 warmup iterations. A conditional-mixture integration check at
    cutoff 132 uses 6000, 12000, and 24000 posterior draws for the three new
    alternatives. Its largest endpoint shift from the 6000-draw result is
    {refinement.max_endpoint_shift_from_6000.max():.3f} response units.
    This is a finite numerical sensitivity check, not proof of predictive calibration.

    Shared discrepancy permits a wider range of population capacities
    (Table~\ref{{tab:structural-capacity}}). Broader capacity uncertainty is
    consistent with confounding between a common trajectory departure and
    the logistic median. The exploratory noise priors do not identify a
    unique physical decomposition. Noise-prior sensitivity, limited trial
    replication, and the unconfirmed physical units remain substantive
    limitations. The next validation step is to freeze the model comparison,
    confirm measurement units and experimental dependence, and assess
    additional independently collected trajectories with forecasts specified
    before inspecting their outcomes. REV-07 remains scientifically open.

\begin{{figure}}[htbp]
    \centering
    \includegraphics[width=\textwidth]{{../results/structural/forecast_comparison.png}}
    \caption{{Matched structural alternatives, reference priors: trial 1
    predictive means and central 90 percent observation intervals. Black
    points are held-out responses. All reported scores use all three trials.}}
    \label{{fig:structural-forecast}}
\end{{figure}}
\begin{{figure}}[htbp]
    \centering
    \includegraphics[width=0.9\textwidth]{{../results/structural/capacity_discrepancy.png}}
    \caption{{Full-data reference posterior samples for capacity and discrepancy
    amplitude under independent and shared OU assumptions. The shared model
    allows greater uncertainty in the population capacity.}}
    \label{{fig:structural-capacity}}
\end{{figure}}
"""
    Path("docs/generated/structural_interpretation.tex").write_text(interpretation)


if __name__ == "__main__":
    main()
